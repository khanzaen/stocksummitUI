    function copyTwibbonCaption() {
        const captionText = `[ WARRIOR OF STOCK SUMMIT UI 2026 ] 📊🔥

Hello everyone! I’m … and I’m ready to step up my adventure! I’m officially ready to compete with top minds across the nation in Stock Summit UI 2026.

Are you ready to test your financial instincts, too? Join me and prove your strategies! 📈⚡

🔗 Register now!
https://stocksummitui.com

🔗 Booklet

* Trading Competition: http://Bit.ly/BookletTCSSUI26
* Equity Research Competition: http://Bit.ly/BookletERCSSUI26

Follow us for more! @stocksummit.ui

📞 CP: Hafizh (0813-8615-1520) | Ilham (0858-8800-9171)

#StockSummitUI2026 #SSUI2026 #EquityResearchCompetition #TradingCompetition #shapingmarketshapingfuture`;

        const copyBtnText = document.getElementById('copy-btn-text');
        const copyIcon = document.getElementById('copy-icon');
        const copiedIcon = document.getElementById('copied-icon');
        const copyBtn = document.getElementById('btn-copy-twibbon-caption');

        const onSuccess = () => {
            if (copyBtnText) copyBtnText.textContent = 'Caption Tersalin!';
            if (copyIcon) copyIcon.classList.add('hidden');
            if (copiedIcon) copiedIcon.classList.remove('hidden');
            if (copyBtn) {
                copyBtn.classList.add('border-emerald-500', 'text-emerald-400');
                copyBtn.classList.remove('text-[#af8a3c]');
            }

            setTimeout(() => {
                if (copyBtnText) copyBtnText.textContent = 'Salin Caption';
                if (copyIcon) copyIcon.classList.remove('hidden');
                if (copiedIcon) copiedIcon.classList.add('hidden');
                if (copyBtn) {
                    copyBtn.classList.remove('border-emerald-500', 'text-emerald-400');
                    copyBtn.classList.add('text-[#af8a3c]');
                }
            }, 2500);
        };

        if (navigator.clipboard && window.isSecureContext) {
            navigator.clipboard.writeText(captionText).then(onSuccess).catch(() => {
                fallbackCopy(captionText, onSuccess);
            });
        } else {
            fallbackCopy(captionText, onSuccess);
        }
    }

    function fallbackCopy(text, callback) {
        const textArea = document.createElement("textarea");
        textArea.value = text;
        textArea.style.position = "fixed";
        textArea.style.left = "-999999px";
        textArea.style.top = "-999999px";
        document.body.appendChild(textArea);
        textArea.focus();
        textArea.select();
        try {
            document.execCommand('copy');
            if (callback) callback();
        } catch (err) {
            console.error('Fallback copy failed', err);
        }
        document.body.removeChild(textArea);
    }
</script>
